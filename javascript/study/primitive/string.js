// 文字列について

// pythonと違い、プリミティブというオブジェクトではない型がある。
// プリミティブはオブジェクトと違い、シンプルな単一な型
// 文字列(String)はプリミティブ型

// 文字列の定義方法
// ↓どれでも変わらない
let str1 = "ダブルクォートで囲んだら文字列になります";
let str2 = "シングルクォートで囲んでも文字列になります";
let str3 = `バッククォートで囲んでも文字列になります`;

// 文字列同士は + で結合できる
let firstName = "太郎";
let lastName = "山田";
console.log(lastName + firstName);

// シングルクォートやダブルクォートを文字列として表示したい場合は別のクォーとで囲んだら良い
console.log('私は"カレー"が好きです。');

// 改行したい場合は(\n)
console.log("user1\nuser2");


