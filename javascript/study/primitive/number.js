// 数値について

// 10進数を定義したい場合は、0〜9 の数字をそのまま書けば number になる。
// 整数も小数も負の数も、全部まとめて number 型。
// pythonみたいに intとfloatが分かれたりとかはない

let num = 10;

// 指数表記(3e6 は 3×10⁶ = 3000000 のこと)
// e のうしろの数字がゼロの数を表す
console.log(3e6);

// 演算子

// 足し算(+)
console.log(4 + 6);

// 引き算(-)
console.log(7 - 4);

// 掛け算(*)
console.log(3 * 4);

// 割り算(/)
console.log(13 / 4);

// 割り算の余り(%)
console.log(13 % 4);

// 累乗(**)
console.log(10 ** 3);
